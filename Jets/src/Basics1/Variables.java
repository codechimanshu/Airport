package Basics1;

public class Variables {
    static void main() {
        int x = 1;
        System.out.println(x);
        int y = 2;
        System.out.println(y);
        int z;        //Declaration
        z = x+y;      //Initialization
        System.out.println(z);
        System.out.println(x*y);
        System.out.println(y*2);

        int a;
        a = 5;
        System.out.println(a);
        a = 6;
        System.out.println(a);
    }
}
